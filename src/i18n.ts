/**
 * Translations.
 *
 * The locale is a module-level value rather than a context: strings are needed
 * in plain functions too (tool descriptions, network errors, the system prompt),
 * and those have no React tree to read from. `App` keeps the language in state
 * and calls `setLocale` before rendering, so a change still re-renders the tree.
 */

export type Lang = "en" | "ru";

export const LANGS: Array<{ id: Lang; name: string }> = [
  { id: "en", name: "English" },
  { id: "ru", name: "Русский" },
];

let locale: Lang = "en";

export function setLocale(l: Lang): void {
  locale = l === "ru" ? "ru" : "en";
}

export function getLocale(): Lang {
  return locale;
}

/**
 * Looks a key up in the active language, falling back to English and then to
 * the key itself, so a missing translation is visible rather than blank.
 * `{name}` placeholders are replaced from `vars`.
 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const table = locale === "ru" ? RU : EN;
  let s = table[key] ?? EN[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  }
  return s;
}

/** Whether a key exists at all, for optional strings like provider blurbs. */
export function has(key: string): boolean {
  return key in EN || key in RU;
}

